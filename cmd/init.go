package cmd

import (
	"bufio"
	"fmt"
	"os"
	"strings"

	"github.com/spf13/cobra"
)

var initCmd = &cobra.Command{
	Use:   "init",
	Short: "Interactive configuration wizard",
	Long:  "Create a new auto-ingress.yaml configuration file interactively.",
	RunE:  runInit,
}

var (
	initFromEnv     string
	initDNSProvider string
)

func init() {
	initCmd.Flags().StringVar(&initFromEnv, "from-env", "", "import from existing .env file")
	initCmd.Flags().StringVar(&initDNSProvider, "dns-provider", "", "DNS provider (tencentcloud|aliyun|cloudflare|route53)")
}

func runInit(cmd *cobra.Command, args []string) error {
	o := out()
	o.Header("Auto Ingress Configuration Wizard")
	fmt.Println()

	reader := bufio.NewReader(os.Stdin)

	// Check if config already exists
	if _, err := os.Stat("auto-ingress.yaml"); err == nil {
		fmt.Print("auto-ingress.yaml already exists. Overwrite? [y/N]: ")
		answer, _ := reader.ReadString('\n')
		answer = strings.TrimSpace(strings.ToLower(answer))
		if answer != "y" && answer != "yes" {
			o.Info("Aborted.")
			return nil
		}
	}

	// Collect configuration
	email := prompt(reader, "ACME email (for Let's Encrypt)", "")
	if email == "" {
		return fmt.Errorf("email is required")
	}

	provider := initDNSProvider
	if provider == "" {
		provider = prompt(reader, "DNS provider", "tencentcloud")
	}

	supported := map[string]bool{
		"tencentcloud": true, "aliyun": true, "cloudflare": true,
		"route53": true, "digitalocean": true, "googlecloud": true,
	}
	if !supported[provider] {
		return fmt.Errorf("unsupported DNS provider: %s (supported: tencentcloud, aliyun, cloudflare, route53, digitalocean, googlecloud)", provider)
	}

	domain := prompt(reader, "Domain (e.g. example.com)", "")
	upstream := prompt(reader, "Upstream service (e.g. web:3000)", "")
	network := prompt(reader, "Docker network", "auto-ingress-upstream")

	// Generate config
	cfg := fmt.Sprintf(`# Auto Ingress Configuration
# Generated by: auto-ingress init
version: "1"

gateway:
  email: %s
  http_bind: "0.0.0.0:80"
  https_bind: "0.0.0.0:443"
  admin_bind: "127.0.0.1:2019"
  memory_limit: 256m
  pids_limit: 256

dns:
  provider: %s

sites:
  - domain: %s
    upstream: %s

security:
  hsts: true
  x_frame_options: SAMEORIGIN
  content_type_nosniff: true
  referrer_policy: strict-origin-when-cross-origin
  hide_server_header: true

discovery:
  enabled: false
  network: %s

logging:
  access:
    enabled: true
    format: json
    output: stdout
  level: info
`, email, provider, domain, upstream, network)

	if err := os.WriteFile("auto-ingress.yaml", []byte(cfg), 0644); err != nil {
		return fmt.Errorf("write config: %w", err)
	}

	fmt.Println()
	o.Success("Configuration saved to auto-ingress.yaml")
	fmt.Println()
	o.Info("Next steps:")
	fmt.Println("  1. Set DNS credentials as environment variables")
	fmt.Printf("  2. auto-ingress site add %s %s\n", domain, upstream)
	fmt.Println("  3. auto-ingress up")

	return nil
}

func prompt(reader *bufio.Reader, question, defaultVal string) string {
	if defaultVal != "" {
		fmt.Printf("%s [%s]: ", question, defaultVal)
	} else {
		fmt.Printf("%s: ", question)
	}
	answer, _ := reader.ReadString('\n')
	answer = strings.TrimSpace(answer)
	if answer == "" && defaultVal != "" {
		return defaultVal
	}
	return answer
}
